#!/usr/bin/env node
/* Builds the self-hosted fonts for the React app (docs/redesign.md → Fonts).
     node tools/fonts.mjs
   Writes src/styles/fonts/ (git-ignored): woff2 files + fonts.css.
   Sources are npm packages pinned in package-lock.json, so CI and local builds produce the same files:
     Plus Jakarta Sans  @fontsource-variable/plus-jakarta-sans  (variable wght, latin + latin-ext)
     Noto Sans JP       @expo-google-fonts/noto-sans-jp          (full TTF, subset here to the glyphs we use)
   Satoshi is not on npm; see the Status section of docs/redesign.md. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src/styles/fonts");
const NM = path.join(ROOT, "node_modules");

/* Every character the app can show in Japanese comes from levels/ and kb/ (content) or src/ (UI strings). */
const SCAN = [["levels", /\.js$/], ["kb", /\.(json|md)$/], ["src", /\.(ts|tsx)$/], ["app", /\.html$/]];
function walk(dir, re, acc) {
  if (!fs.existsSync(dir)) return acc;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (p !== OUT) walk(p, re, acc); }
    else if (re.test(e.name)) acc.push(p);
  }
  return acc;
}
const chars = new Set();
for (let c = 0x20; c <= 0x7e; c++) chars.add(String.fromCodePoint(c)); // full printable ASCII: no per-glyph font mixing inside Latin words
for (const [dir, re] of SCAN) for (const f of walk(path.join(ROOT, dir), re, [])) for (const ch of fs.readFileSync(f, "utf8")) if (ch.codePointAt(0) >= 0x20) chars.add(ch);
const text = [...chars].sort().join("");

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const faces = [];

/* Plus Jakarta Sans: copy the variable latin + latin-ext files with their unicode ranges. */
const PJ = path.join(NM, "@fontsource-variable/plus-jakarta-sans");
const ranges = JSON.parse(fs.readFileSync(path.join(PJ, "unicode.json"), "utf8"));
for (const sub of ["latin", "latin-ext"]) {
  const file = `plus-jakarta-sans-${sub}-wght-normal.woff2`;
  fs.copyFileSync(path.join(PJ, "files", file), path.join(OUT, file));
  faces.push(`@font-face{font-family:"Plus Jakarta Sans";font-style:normal;font-display:swap;font-weight:200 800;src:url("./${file}") format("woff2");unicode-range:${ranges[sub]};}`);
}

/* Noto Sans JP: subset 400 and 700 (500 resolves to 400 by the CSS font-matching rules). */
const NOTO = path.join(NM, "@expo-google-fonts/noto-sans-jp");
let jpBytes = 0;
for (const [w, dir] of [[400, "400Regular"], [700, "700Bold"]]) {
  const src = fs.readFileSync(path.join(NOTO, dir, `NotoSansJP_${dir}.ttf`));
  const out = await subsetFont(src, text, { targetFormat: "woff2" });
  const file = `noto-sans-jp-subset-${w}.woff2`;
  fs.writeFileSync(path.join(OUT, file), out);
  jpBytes += out.length;
  faces.push(`@font-face{font-family:"Noto Sans JP Subset";font-style:normal;font-display:swap;font-weight:${w};src:url("./${file}") format("woff2");}`);
}

fs.writeFileSync(path.join(OUT, "fonts.css"), `/* Generated by tools/fonts.mjs. Do not edit. */\n${faces.join("\n")}\n`);
console.log(`fonts ok: ${chars.size} glyphs in the Noto Sans JP subset, ${(jpBytes / 1024).toFixed(0)} KB for 2 weights`);
