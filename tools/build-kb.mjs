#!/usr/bin/env node
/* Builds js/kb.js and kb/STATUS.md from kb/, and checks that every level item
   points at a real rule. No dependencies.
     node tools/build-kb.mjs          write outputs
     node tools/build-kb.mjs --check  fail if outputs are stale or anything is invalid (CI) */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rd = p => fs.readFileSync(path.join(ROOT, p), "utf8");
const json = p => { try { return JSON.parse(rd(p)); } catch (e) { fail(`${p}: invalid JSON (${e.message})`); } };
const errors = [], warnings = [];
function fail(m) { errors.push(m); }
const STATUSES = ["primary", "secondary", "unverified"];

/* ---------- load ---------- */
const sources = json("kb/sources.json");
const rules = {};
for (const f of fs.readdirSync(path.join(ROOT, "kb/rules")).filter(f => f.endsWith(".json")).sort()) {
  const topic = f.replace(/\.json$/, "");
  const list = json(`kb/rules/${f}`) || [];
  if (!Array.isArray(list)) { fail(`kb/rules/${f}: must be an array`); continue; }
  for (const r of list) {
    const where = `kb/rules/${f} › ${r.id || "(no id)"}`;
    for (const k of ["id", "en", "ja", "refs", "status"]) if (r[k] == null || r[k] === "") fail(`${where}: missing "${k}"`);
    if (rules[r.id]) fail(`${where}: duplicate id (also in ${rules[r.id].topic})`);
    if (!STATUSES.includes(r.status)) fail(`${where}: status must be one of ${STATUSES.join(", ")}`);
    for (const ref of r.refs || []) if (!sources[ref.src]) fail(`${where}: unknown source "${ref.src}"`);
    if (r.status === "primary" && !(r.refs || []).some(x => sources[x.src]?.kind === "primary" && x.src !== "rta" && x.src !== "rta-order"))
      fail(`${where}: "primary" needs a ref to official text that was actually read (kyosoku)`);
    rules[r.id] = { ...r, topic };
  }
}
const vocab = {};
for (const f of fs.readdirSync(path.join(ROOT, "kb/vocab")).filter(f => f.endsWith(".json")).sort()) {
  const v = json(`kb/vocab/${f}`); vocab[f.replace(/\.json$/, "")] = v;
  if (f === "sign-kanji.json") {
    const words = new Set(v.words.map(w => w.w));
    for (const w of v.readingDrill) if (!words.has(w)) fail(`kb/vocab/${f}: readingDrill "${w}" is not in words`);
    for (const b of v.build) {
      if (!words.has(b.w)) fail(`kb/vocab/${f}: build "${b.w}" is not in words`);
      if (b.tiles.join("") !== b.w) fail(`kb/vocab/${f}: build "${b.w}" tiles spell "${b.tiles.join("")}"`);
      for (const d of b.decoys) if (b.tiles.includes(d)) fail(`kb/vocab/${f}: build "${b.w}" decoy "${d}" is also a real tile`);
    }
  }
}

/* ---------- check level files ---------- */
const ctx = { CHAPTERS: [], KB: { rules, sources, vocab }, G: { stopY: 0, cwS: { y1: 0 }, box: { y1: 0 } }, console };
vm.createContext(ctx);
const html = rd("index.html");
const levelFiles = [...html.matchAll(/<script src="(levels\/[^"]+)"/g)].map(m => m[1]);
for (const f of levelFiles) {
  try { vm.runInContext(rd(f), ctx, { filename: f }); } catch (e) { fail(`${f}: ${e.message}`); }
}
const used = new Set();
let ruleItems = 0;
for (const C of ctx.CHAPTERS) {
  if (C.rules === false) continue;
  for (const L of C.levels) {
    if (L.id === "sort") { used.add("sign.kinds"); for (const k of ["kisei", "shiji", "keikai", "annai"]) used.add("sign.kind." + k); continue; }
    L.items.forEach((it, i) => {
      const ids = [].concat(it.rule || []);
      if (!ids.length) fail(`${C.id}/${L.id}[${i}]: no "rule"`);
      for (const id of ids) { if (!rules[id]) fail(`${C.id}/${L.id}[${i}]: unknown rule "${id}"`); used.add(id); }
      ruleItems++;
    });
  }
}
for (const id of Object.keys(rules)) if (!used.has(id)) warnings.push(`rule "${id}" is not used by any level yet`);

/* ---------- outputs ---------- */
const kbJs = `/* GENERATED by tools/build-kb.mjs from kb/ — do not edit by hand. */\n"use strict";\nconst KB=${JSON.stringify({ sources, rules, vocab })};\n`;
const count = s => Object.values(rules).filter(r => r.status === s).length;
const rows = Object.values(rules).sort((a, b) => STATUSES.indexOf(b.status) - STATUSES.indexOf(a.status) || a.id.localeCompare(b.id));
const cite = r => r.refs.map(x => `${sources[x.src].title}${x.loc ? " " + x.loc : ""}`).join("; ");
const status = `# Knowledge base status\n\n_Generated by \`tools/build-kb.mjs\`. Do not edit by hand._\n\n` +
  `| Status | Meaning | Rules |\n|---|---|---|\n` +
  `| primary | Confirmed in official text that was actually read | ${count("primary")} |\n` +
  `| secondary | From a police or driving-school source that cites the law | ${count("secondary")} |\n` +
  `| unverified | General knowledge, not checked against any source | ${count("unverified")} |\n\n` +
  `${ruleItems} level items reference ${used.size} rules. Kanji vocabulary: ${vocab["sign-kanji"]?.status || "n/a"}.\n\n` +
  `## Rules to verify first (unverified)\n\n| Rule | Statement | Cited |\n|---|---|---|\n` +
  rows.filter(r => r.status === "unverified").map(r => `| \`${r.id}\` | ${r.en.replace(/\|/g, "\\|")} | ${cite(r)} |`).join("\n") +
  `\n\n## Secondary\n\n| Rule | Cited |\n|---|---|\n` +
  rows.filter(r => r.status === "secondary").map(r => `| \`${r.id}\` | ${cite(r)} |`).join("\n") +
  `\n\n## Primary\n\n| Rule | Cited |\n|---|---|\n` +
  rows.filter(r => r.status === "primary").map(r => `| \`${r.id}\` | ${cite(r)} |`).join("\n") + "\n";

const outs = { "js/kb.js": kbJs, "kb/STATUS.md": status };
const check = process.argv.includes("--check");
for (const [p, body] of Object.entries(outs)) {
  const full = path.join(ROOT, p), cur = fs.existsSync(full) ? fs.readFileSync(full, "utf8") : null;
  if (check) { if (cur !== body) fail(`${p} is out of date: run node tools/build-kb.mjs`); }
  else if (cur !== body) fs.writeFileSync(full, body);
}
for (const w of warnings) console.warn("warn:", w);
if (errors.length) { for (const e of errors) console.error("error:", e); process.exit(1); }
console.log(`kb ok: ${Object.keys(rules).length} rules (${count("primary")} primary, ${count("secondary")} secondary, ${count("unverified")} unverified), ${ruleItems} level items linked${check ? " — outputs up to date" : ""}`);
